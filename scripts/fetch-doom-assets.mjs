// Fetches the Doom WebAssembly build and the shareware WAD from npm, verifies them
// against pinned checksums, and wraps them as TypeScript modules in
// src/client/generated/ so the Now SDK client bundler can ship them as UI assets.
//
// Nothing downloaded here is committed (see .gitignore): run `npm run assets` after cloning.
//
// Each *.ts module default-exports gzip+base64 text (except the tiny config).
//   engine: Emscripten/Chocolate Doom ("doom-wasm", GPL-2.0+), via @nicejsisverycool/tizendoom
//   wad:    DOOM1.WAD, id Software's v1.9 shareware episode, freely redistributable unmodified
import { createHash } from 'node:crypto'
import { gzipSync } from 'node:zlib'
import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { basename, dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const vendor = join(root, 'vendor', 'tizendoom')
const outDir = join(root, 'src', 'client', 'generated')

const PACKAGE = '@nicejsisverycool/tizendoom@0.1.6'
const FILES = {
    'doom1.wad': '1d7d43be501e67d927e415e0b8f3e29c3bf33075e859721816f652a526cac771',
    'websockets-doom.wasm': '6366f83a58fe8596ce742a66dbf86871d315862c89c11e65b54935be03c7e6c4',
    'websockets-doom.js': 'a2909044a9fbc5529f941c8dbf93cc2931927690e0341c737545cf0b9cff23fb',
    'default.cfg': '80bc17bdc9077d2caeeb8b5345aa314faa119f6deb0dcb3c9f97851741277b2b',
}

const sha256 = (buf) => createHash('sha256').update(buf).digest('hex')
const pkgDir = join(vendor, 'package')

function download() {
    rmSync(vendor, { recursive: true, force: true })
    mkdirSync(vendor, { recursive: true })
    const npm = process.platform === 'win32' ? 'npm.cmd' : 'npm'
    const out = execFileSync(npm, ['pack', PACKAGE, '--silent', '--pack-destination', vendor], { encoding: 'utf8', shell: process.platform === 'win32' })
    const tarball = join(vendor, out.trim().split('\n').pop())
    execFileSync('tar', ['-xzf', basename(tarball)], { cwd: vendor })
}

function verify() {
    for (const [file, expected] of Object.entries(FILES)) {
        const actual = sha256(readFileSync(join(pkgDir, file)))
        if (actual !== expected) {
            throw new Error(`${file}: sha256 mismatch\n  expected ${expected}\n  actual   ${actual}`)
        }
    }
    const wad = readFileSync(join(pkgDir, 'doom1.wad'))
    if (wad.subarray(0, 4).toString('latin1') !== 'IWAD') throw new Error('doom1.wad is not an IWAD')
}

function emit(name, source) {
    writeFileSync(join(outDir, name), source)
    console.log(`  src/client/generated/${name}  ${(source.length / 1024 / 1024).toFixed(2)} MB`)
}

if (!existsSync(join(pkgDir, 'doom1.wad'))) {
    console.log(`Downloading ${PACKAGE}`)
    download()
}
verify()
console.log('Checksums verified. Generating modules:')

mkdirSync(outDir, { recursive: true })
// Gzipped before base64 to roughly halve what is installed; the browser inflates with DecompressionStream.
const gz64 = (file) => gzipSync(readFileSync(join(pkgDir, file)), { level: 9 }).toString('base64')
const banner = '// GENERATED by scripts/fetch-doom-assets.mjs. Do not edit or commit.\n'

emit('engine-wasm.ts', `${banner}export default '${gz64('websockets-doom.wasm')}'\n`)
emit('game-wad.ts', `${banner}export default '${gz64('doom1.wad')}'\n`)
emit('engine-glue.ts', `${banner}export default '${gz64('websockets-doom.js')}'\n`)
emit('game-cfg.ts', `${banner}export default ${JSON.stringify(readFileSync(join(pkgDir, 'default.cfg'), 'utf8'))}\n`)
